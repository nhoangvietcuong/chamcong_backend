/* ============================================================
   HỆ THỐNG CHẤM CÔNG NHÂN VIÊN KỸ THUẬT HIỆN TRƯỜNG - PWA
   PostgreSQL - Bản chốt không quản lý ca làm việc

   Phạm vi nghiệp vụ:
   - Quản trị viên chỉ phân công địa điểm chấm công cho nhân viên theo ngày.
   - Không quản lý ca làm việc.
   - Không tính đi trễ hoặc về sớm.
   - Mỗi nhân viên tối đa 01 phân công trong một ngày.
   - Mỗi phân công tương ứng tối đa 01 bản ghi chấm công.
   - Mỗi bản ghi gồm 01 lần check-in và 01 lần check-out.
   - Thời gian chấm công trực tuyến do backend/server ghi nhận.
   - Payload ngoại tuyến có client_request_id để chống xử lý trùng.
   - Nhật ký vị trí lưu snapshot tọa độ mục tiêu và bán kính áp dụng.
   - Các mốc thời gian nghiệp vụ sử dụng TIMESTAMPTZ.
   ============================================================ */

BEGIN;

/* ============================================================
   0. XÓA CẤU TRÚC CŨ
   CẢNH BÁO: Các lệnh này xóa toàn bộ bảng và dữ liệu hiện có.
   ============================================================ */
DROP TABLE IF EXISTS public.system_logs CASCADE;
DROP TABLE IF EXISTS public.employee_face_profiles CASCADE;
DROP TABLE IF EXISTS public.employee_webauthn_credentials CASCADE;
DROP TABLE IF EXISTS public.attendance_location_logs CASCADE;
DROP TABLE IF EXISTS public.attendance CASCADE;
DROP TABLE IF EXISTS public.employee_work_assignments CASCADE;
DROP TABLE IF EXISTS public.work_locations CASCADE;
DROP TABLE IF EXISTS public.registered_devices CASCADE;
DROP TABLE IF EXISTS public.user_sessions CASCADE;
DROP TABLE IF EXISTS public.accounts CASCADE;
DROP TABLE IF EXISTS public.employees CASCADE;
DROP TABLE IF EXISTS public.shifts CASCADE;
DROP TABLE IF EXISTS public.roles CASCADE;
DROP TABLE IF EXISTS public.departments CASCADE;

DROP FUNCTION IF EXISTS public.set_updated_at() CASCADE;

/* ============================================================
   1. DEPARTMENTS
   Lưu thông tin phòng ban.
   ============================================================ */
CREATE TABLE public.departments (
    department_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL,
    description     VARCHAR(255),
    status          SMALLINT NOT NULL DEFAULT 1,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_departments_name
        UNIQUE (department_name),

    CONSTRAINT ck_departments_status
        CHECK (status IN (0, 1))
);

/* ============================================================
   2. ROLES
   Hệ thống sử dụng ba vai trò cố định.
   ============================================================ */
CREATE TABLE public.roles (
    role_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_roles_name
        UNIQUE (role_name),

    CONSTRAINT ck_roles_name
        CHECK (role_name IN ('SUPMANAGER', 'ADMIN', 'MANAGER', 'EMPLOYEE'))
);

/* ============================================================
   3. EMPLOYEES
   Không có shift_id vì hệ thống không quản lý ca.
   ============================================================ */
CREATE TABLE public.employees (
    employee_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(20) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(100),
    phone         VARCHAR(20),
    department_id BIGINT NOT NULL,
    status        SMALLINT NOT NULL DEFAULT 1,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_employees_code
        UNIQUE (employee_code),

    CONSTRAINT fk_employees_department
        FOREIGN KEY (department_id)
        REFERENCES public.departments(department_id),

    CONSTRAINT ck_employees_status
        CHECK (status IN (0, 1)),

    CONSTRAINT ck_employees_email_not_blank
        CHECK (email IS NULL OR BTRIM(email) <> ''),

    CONSTRAINT ck_employees_phone_not_blank
        CHECK (phone IS NULL OR BTRIM(phone) <> '')
);

CREATE INDEX idx_employees_department
ON public.employees(department_id);

CREATE INDEX idx_employees_status
ON public.employees(status);

/* Email được xem là không phân biệt chữ hoa/chữ thường. */
CREATE UNIQUE INDEX uq_employees_email_ci
ON public.employees(LOWER(email))
WHERE email IS NOT NULL;

/* ============================================================
   4. ACCOUNTS
   Mỗi nhân viên có tối đa một tài khoản.
   ============================================================ */
CREATE TABLE public.accounts (
    account_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT NOT NULL,
    username      VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role_id       BIGINT NOT NULL,
    is_active     SMALLINT NOT NULL DEFAULT 1,
    require_password_change BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_accounts_employee
        UNIQUE (employee_id),

    /* Dùng cho khóa ngoại kết hợp của user_sessions. */
    CONSTRAINT uq_accounts_account_employee
        UNIQUE (account_id, employee_id),

    CONSTRAINT fk_accounts_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees(employee_id),

    CONSTRAINT fk_accounts_role
        FOREIGN KEY (role_id)
        REFERENCES public.roles(role_id),

    CONSTRAINT ck_accounts_active
        CHECK (is_active IN (0, 1)),

    CONSTRAINT ck_accounts_username_not_blank
        CHECK (BTRIM(username) <> ''),

    CONSTRAINT ck_accounts_password_hash_not_blank
        CHECK (BTRIM(password_hash) <> '')
);

CREATE INDEX idx_accounts_role
ON public.accounts(role_id);

CREATE INDEX idx_accounts_active
ON public.accounts(is_active);

/* Username không phân biệt chữ hoa/chữ thường. */
CREATE UNIQUE INDEX uq_accounts_username_ci
ON public.accounts(LOWER(username));

/* ============================================================
   5. USER_SESSIONS
   Kiểm soát một tài khoản chỉ có một phiên ACTIVE.
   ============================================================ */
CREATE TABLE public.user_sessions (
    session_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT NOT NULL,
    employee_id        BIGINT NOT NULL,
    device_fingerprint VARCHAR(255) NOT NULL,
    device_name        VARCHAR(255),
    ip_address         VARCHAR(50),
    login_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at         TIMESTAMPTZ NOT NULL,
    logout_at          TIMESTAMPTZ,
    session_status     VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    refresh_token_hash VARCHAR(255),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sessions_account_employee
        FOREIGN KEY (account_id, employee_id)
        REFERENCES public.accounts(account_id, employee_id),

    CONSTRAINT ck_sessions_status
        CHECK (
            session_status IN (
                'ACTIVE',
                'EXPIRED',
                'LOGGED_OUT',
                'REPLACED',
                'REVOKED'
            )
        ),

    CONSTRAINT ck_sessions_expiration
        CHECK (expires_at > login_at),

    CONSTRAINT ck_sessions_last_activity
        CHECK (last_activity_at >= login_at),

    CONSTRAINT ck_sessions_logout_time
        CHECK (logout_at IS NULL OR logout_at >= login_at),

    CONSTRAINT ck_sessions_device_fingerprint_not_blank
        CHECK (BTRIM(device_fingerprint) <> '')
);

/* Một tài khoản chỉ có một phiên ACTIVE tại một thời điểm. */
CREATE UNIQUE INDEX uq_sessions_one_active_per_account
ON public.user_sessions(account_id)
WHERE session_status = 'ACTIVE';

CREATE INDEX idx_sessions_employee
ON public.user_sessions(employee_id);

CREATE INDEX idx_sessions_status
ON public.user_sessions(session_status);

CREATE INDEX idx_sessions_expires_at
ON public.user_sessions(expires_at);

/* ============================================================
   6. REGISTERED_DEVICES
   Lưu lịch sử và trạng thái thiết bị logic đã sử dụng.
   ============================================================ */
CREATE TABLE public.registered_devices (
    device_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id        BIGINT NOT NULL,
    device_fingerprint VARCHAR(255) NOT NULL,
    device_name        VARCHAR(255),
    is_verified        SMALLINT NOT NULL DEFAULT 0,
    registered_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_devices_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees(employee_id),

    CONSTRAINT uq_devices_employee_fingerprint
        UNIQUE (employee_id, device_fingerprint),

    CONSTRAINT ck_devices_verified
        CHECK (is_verified IN (0, 1)),

    CONSTRAINT ck_devices_fingerprint_not_blank
        CHECK (BTRIM(device_fingerprint) <> ''),

    CONSTRAINT ck_devices_last_used_time
        CHECK (last_used_at IS NULL OR last_used_at >= registered_at)
