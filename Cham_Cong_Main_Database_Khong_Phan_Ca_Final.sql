/* ============================================================
   9. ATTENDANCE
   Không có is_late, is_early_leave hoặc thông tin ca.
   ============================================================ */
CREATE TABLE public.attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT NOT NULL,
    assignment_id BIGINT NOT NULL,
    work_date     DATE NOT NULL,

    check_in_time  TIMESTAMPTZ,
    check_out_time TIMESTAMPTZ,

    /* Thời gian phía client chỉ dùng tham chiếu, nhất là offline. */
    client_check_in_time  TIMESTAMPTZ,
    client_check_out_time TIMESTAMPTZ,

    check_in_latitude  DECIMAL(10,7),
    check_in_longitude DECIMAL(10,7),
    check_out_latitude DECIMAL(10,7),
    check_out_longitude DECIMAL(10,7),

    check_in_gps_accuracy  DECIMAL(10,2),
    check_out_gps_accuracy DECIMAL(10,2),

    check_in_distance_meter  DECIMAL(10,2),
    check_out_distance_meter DECIMAL(10,2),

    check_in_photo_url  TEXT,
    check_out_photo_url TEXT,

    is_offline_sync     SMALLINT NOT NULL DEFAULT 0,
    location_trust_score INTEGER,
    risk_level           VARCHAR(20),

    attendance_status VARCHAR(30) NOT NULL DEFAULT 'IN_PROGRESS',

    review_status VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUIRED',
    reviewed_by   BIGINT,
    reviewed_at   TIMESTAMPTZ,
    review_note   VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    /* Một phân công chỉ có một bản ghi attendance. */
    CONSTRAINT uq_attendance_assignment
        UNIQUE (assignment_id),

    /* Một nhân viên chỉ có một bản ghi attendance trong một ngày. */
    CONSTRAINT uq_attendance_employee_date
        UNIQUE (employee_id, work_date),

    /* Dùng cho khóa ngoại kết hợp của attendance_location_logs. */
    CONSTRAINT uq_attendance_log_context
        UNIQUE (attendance_id, employee_id, assignment_id),

    /* Bảo đảm attendance gắn đúng nhân viên và đúng ngày của assignment. */
    CONSTRAINT fk_attendance_assignment_context
        FOREIGN KEY (assignment_id, employee_id, work_date)
        REFERENCES public.employee_work_assignments(
            assignment_id,
            employee_id,
            work_date
        ),

    CONSTRAINT fk_attendance_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES public.accounts(account_id),

    CONSTRAINT ck_attendance_check_in_latitude
        CHECK (
            check_in_latitude IS NULL
            OR check_in_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_attendance_check_in_longitude
        CHECK (
            check_in_longitude IS NULL
            OR check_in_longitude BETWEEN -180 AND 180
        ),

    CONSTRAINT ck_attendance_check_out_latitude
        CHECK (
            check_out_latitude IS NULL
            OR check_out_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_attendance_check_out_longitude
        CHECK (
            check_out_longitude IS NULL
            OR check_out_longitude BETWEEN -180 AND 180
        ),

    CONSTRAINT ck_attendance_check_in_accuracy
        CHECK (
            check_in_gps_accuracy IS NULL
            OR check_in_gps_accuracy >= 0
        ),

    CONSTRAINT ck_attendance_check_out_accuracy
        CHECK (
            check_out_gps_accuracy IS NULL
            OR check_out_gps_accuracy >= 0
        ),

    CONSTRAINT ck_attendance_check_in_distance
        CHECK (
            check_in_distance_meter IS NULL
            OR check_in_distance_meter >= 0
        ),

    CONSTRAINT ck_attendance_check_out_distance
        CHECK (
            check_out_distance_meter IS NULL
            OR check_out_distance_meter >= 0
        ),

    CONSTRAINT ck_attendance_offline
        CHECK (is_offline_sync IN (0, 1)),

    CONSTRAINT ck_attendance_trust_score
        CHECK (
            location_trust_score IS NULL
            OR location_trust_score BETWEEN 0 AND 100
        ),

    CONSTRAINT ck_attendance_risk
        CHECK (
            risk_level IS NULL
            OR risk_level IN ('LOW', 'MEDIUM', 'HIGH')
        ),

    CONSTRAINT ck_attendance_status
        CHECK (
            attendance_status IN (
                'IN_PROGRESS',
                'COMPLETED',
                'INVALID',
                'REVIEW_REQUIRED'
            )
        ),

    CONSTRAINT ck_attendance_review_status
        CHECK (
            review_status IN (
                'NOT_REQUIRED',
                'PENDING',
                'APPROVED',
                'REJECTED'
            )
        ),

    /* Check-out không được xảy ra trước check-in. */
    CONSTRAINT ck_attendance_time_order
        CHECK (
            check_out_time IS NULL
            OR (
                check_in_time IS NOT NULL
                AND check_out_time >= check_in_time
            )
        ),

    /* Đồng bộ trạng thái attendance với các mốc thời gian. */
    CONSTRAINT ck_attendance_status_time
        CHECK (
            (
                attendance_status = 'IN_PROGRESS'
                AND check_in_time IS NOT NULL
                AND check_out_time IS NULL
            )
            OR (
                attendance_status = 'COMPLETED'
                AND check_in_time IS NOT NULL
                AND check_out_time IS NOT NULL
            )
            OR (
                attendance_status IN ('INVALID', 'REVIEW_REQUIRED')
                AND check_in_time IS NOT NULL
            )
        ),

    /*
       Quy tắc hậu kiểm:
       - REVIEW_REQUIRED phải ở trạng thái PENDING.
       - COMPLETED bình thường dùng NOT_REQUIRED.
       - Sau khi duyệt:
         + APPROVED đi cùng COMPLETED.
         + REJECTED đi cùng INVALID.
    */
    CONSTRAINT ck_attendance_review_consistency
        CHECK (
            (
                attendance_status = 'REVIEW_REQUIRED'
                AND review_status = 'PENDING'
            )
            OR (
                attendance_status = 'COMPLETED'
                AND review_status IN ('NOT_REQUIRED', 'APPROVED')
            )
            OR (
                attendance_status = 'INVALID'
                AND review_status = 'REJECTED'
            )
            OR (
                attendance_status = 'IN_PROGRESS'
                AND review_status = 'NOT_REQUIRED'
            )
        ),

    CONSTRAINT ck_attendance_review_information
        CHECK (
            (
                review_status IN ('NOT_REQUIRED', 'PENDING')
                AND reviewed_by IS NULL
                AND reviewed_at IS NULL
            )
            OR (
                review_status IN ('APPROVED', 'REJECTED')
                AND reviewed_by IS NOT NULL
                AND reviewed_at IS NOT NULL
            )
        ),

    CONSTRAINT ck_attendance_review_note
        CHECK (
            review_note IS NULL
            OR BTRIM(review_note) <> ''
        )
);

CREATE INDEX idx_attendance_status
ON public.attendance(attendance_status);

CREATE INDEX idx_attendance_review_status
ON public.attendance(review_status);

CREATE INDEX idx_attendance_created_at
ON public.attendance(created_at);

/* ============================================================
   10. ATTENDANCE_LOCATION_LOGS
   Lưu dấu vết cho từng request check-in/check-out,
   kể cả request bị từ chối.
   ============================================================ */
CREATE TABLE public.attendance_location_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /* Chống xử lý lặp cùng một payload từ PWA/IndexedDB. */
    client_request_id UUID,

    attendance_id BIGINT,
    employee_id   BIGINT NOT NULL,
    session_id    BIGINT,
    assignment_id BIGINT,
    location_id   BIGINT,

    action_type VARCHAR(20) NOT NULL,

    /* Vị trí nhân viên do client gửi. */
    latitude    DECIMAL(10,7),
    longitude   DECIMAL(10,7),
    gps_accuracy DECIMAL(10,2),

    /* Snapshot địa điểm và bán kính dùng khi xác thực. */
    target_latitude       DECIMAL(10,7),
    target_longitude      DECIMAL(10,7),
    applied_radius_meter  INTEGER,
    distance_meter        DECIMAL(10,2),

    device_fingerprint VARCHAR(255),
    is_pwa_standalone  SMALLINT NOT NULL DEFAULT 0,

    captured_at_client TIMESTAMPTZ,
    received_at_server TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    is_offline_payload SMALLINT NOT NULL DEFAULT 0,

    location_trust_score INTEGER,
    validation_result    VARCHAR(30) NOT NULL,
    validation_reason    VARCHAR(500),
    risk_level           VARCHAR(20),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    /* Khi attendance_id có giá trị, context phải khớp attendance. */
    CONSTRAINT fk_logs_attendance_context
        FOREIGN KEY (attendance_id, employee_id, assignment_id)
        REFERENCES public.attendance(
            attendance_id,
            employee_id,
            assignment_id
        ),

    CONSTRAINT fk_logs_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees(employee_id),

    CONSTRAINT fk_logs_session
        FOREIGN KEY (session_id)
        REFERENCES public.user_sessions(session_id),

    /* Bảo đảm assignment_id thuộc đúng employee_id. */
    CONSTRAINT fk_logs_assignment_employee
        FOREIGN KEY (assignment_id, employee_id)
        REFERENCES public.employee_work_assignments(
            assignment_id,
            employee_id
        ),

    CONSTRAINT fk_logs_location
        FOREIGN KEY (location_id)
        REFERENCES public.work_locations(location_id),

    CONSTRAINT ck_logs_action
        CHECK (action_type IN ('CHECK_IN', 'CHECK_OUT')),

    CONSTRAINT ck_logs_pwa
        CHECK (is_pwa_standalone IN (0, 1)),

    CONSTRAINT ck_logs_offline
        CHECK (is_offline_payload IN (0, 1)),

    CONSTRAINT ck_logs_validation
        CHECK (
            validation_result IN (
                'ACCEPTED',
                'REJECTED',
                'REVIEW_REQUIRED'
            )
        ),

    CONSTRAINT ck_logs_risk
        CHECK (
            risk_level IS NULL
            OR risk_level IN ('LOW', 'MEDIUM', 'HIGH')
        ),

    CONSTRAINT ck_logs_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),

    CONSTRAINT ck_logs_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),

    CONSTRAINT ck_logs_target_latitude
        CHECK (
            target_latitude IS NULL
            OR target_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_logs_target_longitude
        CHECK (
            target_longitude IS NULL
            OR target_longitude BETWEEN -180 AND 180
        ),

    CONSTRAINT ck_logs_accuracy
        CHECK (gps_accuracy IS NULL OR gps_accuracy >= 0),

    CONSTRAINT ck_logs_distance
        CHECK (distance_meter IS NULL OR distance_meter >= 0),

    CONSTRAINT ck_logs_radius
        CHECK (
            applied_radius_meter IS NULL
            OR applied_radius_meter > 0
        ),

    CONSTRAINT ck_logs_trust_score
        CHECK (
            location_trust_score IS NULL
            OR location_trust_score BETWEEN 0 AND 100
        ),

    /* ACCEPTED phải liên kết với attendance chính thức. */
    CONSTRAINT ck_logs_accepted_attendance
        CHECK (
            validation_result <> 'ACCEPTED'
            OR attendance_id IS NOT NULL
        ),

    /* REJECTED hoặc REVIEW_REQUIRED phải ghi rõ lý do. */
    CONSTRAINT ck_logs_validation_reason
        CHECK (
            validation_result = 'ACCEPTED'
            OR (
                validation_reason IS NOT NULL
                AND BTRIM(validation_reason) <> ''
            )
        ),

    /* ACCEPTED phải có đủ dữ liệu đã dùng để kiểm tra geofence. */
    CONSTRAINT ck_logs_accepted_geofence_data
        CHECK (
            validation_result <> 'ACCEPTED'
            OR (
                latitude IS NOT NULL
                AND longitude IS NOT NULL
                AND gps_accuracy IS NOT NULL
                AND target_latitude IS NOT NULL
                AND target_longitude IS NOT NULL
                AND applied_radius_meter IS NOT NULL
                AND distance_meter IS NOT NULL
                AND assignment_id IS NOT NULL
                AND location_id IS NOT NULL
                AND session_id IS NOT NULL
            )
        )
);

