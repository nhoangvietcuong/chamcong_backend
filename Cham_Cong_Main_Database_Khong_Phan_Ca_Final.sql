    allowed_radius_meter INTEGER NOT NULL,
    status               SMALLINT NOT NULL DEFAULT 1,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_locations_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT ck_locations_longitude
        CHECK (longitude BETWEEN -180 AND 180),

    CONSTRAINT ck_locations_radius
        CHECK (allowed_radius_meter > 0),

    CONSTRAINT ck_locations_status
        CHECK (status IN (0, 1)),

    CONSTRAINT ck_locations_name_not_blank
        CHECK (BTRIM(location_name) <> '')
);

CREATE INDEX idx_locations_status
ON public.work_locations(status);

