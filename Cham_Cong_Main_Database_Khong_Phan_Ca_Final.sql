CREATE INDEX idx_devices_employee
ON public.registered_devices(employee_id);

CREATE INDEX idx_devices_verified
ON public.registered_devices(is_verified);

/* ============================================================
   7. WORK_LOCATIONS
   Lưu địa điểm và bán kính chấm công.
   ============================================================ */
CREATE TABLE public.work_locations (
    location_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_name        VARCHAR(100) NOT NULL,
    address              VARCHAR(255),
    latitude             DECIMAL(10,7) NOT NULL,
