const { Pool } = require('pg');
require('dotenv').config();

const pool = new Pool({
  host: process.env.PGHOST,
  port: parseInt(process.env.PGPORT || '5432', 10),
  user: process.env.PGUSER,
  password: process.env.PGPASSWORD,
  database: process.env.PGDATABASE,
  max: 20,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 2000,
});

async function initIndexes() {
  try {
    await pool.query(`
      CREATE INDEX IF NOT EXISTS idx_attendance_assignment_id ON public.attendance(assignment_id);
      CREATE INDEX IF NOT EXISTS idx_attendance_emp_date ON public.attendance(employee_id, work_date);
      CREATE INDEX IF NOT EXISTS idx_logs_client_req_id ON public.attendance_location_logs(client_request_id);
      ALTER TABLE public.employees ADD COLUMN IF NOT EXISTS avatar_url VARCHAR(255);
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS check_in_verification_photo_url TEXT;
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS check_out_verification_photo_url TEXT;
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS review_status VARCHAR(20) DEFAULT 'NOT_REQUIRED';
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS reviewed_by BIGINT;
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ;
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS review_note TEXT;
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS risk_level VARCHAR(20) DEFAULT 'LOW';
      ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS trust_score NUMERIC(5,2);

      CREATE TABLE IF NOT EXISTS public.attendance_photos (
          photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          attendance_id BIGINT REFERENCES public.attendance(attendance_id) ON DELETE SET NULL,
          employee_id BIGINT NOT NULL REFERENCES public.employees(employee_id) ON DELETE CASCADE,
          assignment_id BIGINT REFERENCES public.employee_work_assignments(assignment_id) ON DELETE SET NULL,
          photo_type VARCHAR(50) NOT NULL,
          photo_url TEXT NOT NULL,
          public_id VARCHAR(255),
          captured_at TIMESTAMP WITH TIME ZONE,
          uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          cloud_provider VARCHAR(50) DEFAULT 'LOCAL',
          file_size INT,
          mime_type VARCHAR(100),
          image_width INT,
          image_height INT,
          face_confidence DECIMAL(5,2),
          liveness_score DECIMAL(5,2),
          verification_result VARCHAR(50),
          gps_accuracy DECIMAL(10,2),
          gps_distance DECIMAL(10,2),
          is_deleted INT DEFAULT 0,
          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          CONSTRAINT ck_photo_type CHECK (
              photo_type IN (
                  'LOCATION_BEFORE_FACE',
                  'LOCATION_CAPTURE',
                  'FACE_CAPTURE',
                  'CHECK_IN_FINAL',
                  'CHECK_OUT_FINAL',
                  'OFFLINE_SYNC',
                  'MANUAL_REVIEW',
                  'ADMIN_UPLOAD'
              )
          )
      );

      ALTER TABLE public.attendance_photos DROP CONSTRAINT IF EXISTS ck_photo_type;
      ALTER TABLE public.attendance_photos ADD CONSTRAINT ck_photo_type CHECK (
          photo_type IN (
              'LOCATION_BEFORE_FACE',
              'LOCATION_CAPTURE',
              'FACE_CAPTURE',
              'CHECK_IN_FINAL',
              'CHECK_OUT_FINAL',
              'OFFLINE_SYNC',
              'MANUAL_REVIEW',
              'ADMIN_UPLOAD'
          )
      );

      ALTER TABLE public.leave_requests DROP CONSTRAINT IF EXISTS ck_leave_type;
      ALTER TABLE public.leave_requests ADD CONSTRAINT ck_leave_type CHECK (
          leave_type IN ('ANNUAL', 'COMPENSATORY', 'SICK', 'UNPAID', 'MARRIAGE', 'MATERNITY', 'OTHER')
      );

      CREATE INDEX IF NOT EXISTS idx_attendance_photos_attendance_id ON public.attendance_photos(attendance_id);
      CREATE INDEX IF NOT EXISTS idx_attendance_photos_employee_id ON public.attendance_photos(employee_id);
      CREATE INDEX IF NOT EXISTS idx_attendance_photos_captured_at ON public.attendance_photos(captured_at);
      CREATE INDEX IF NOT EXISTS idx_attendance_photos_photo_type ON public.attendance_photos(photo_type);

      CREATE TABLE IF NOT EXISTS public.push_subscriptions (
        subscription_id SERIAL PRIMARY KEY,
        employee_id INT REFERENCES public.employees(employee_id) ON DELETE CASCADE,
        subscription_json JSONB NOT NULL,
        device_name VARCHAR(100),
        browser VARCHAR(50),
        is_active BOOLEAN DEFAULT TRUE,
        last_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS public.notification_history (
        history_id SERIAL PRIMARY KEY,
        employee_id INT REFERENCES public.employees(employee_id) ON DELETE CASCADE,
        notification_type VARCHAR(50) NOT NULL,
        target_date DATE NOT NULL,
        sent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT uq_emp_type_date UNIQUE (employee_id, notification_type, target_date)
      );

      CREATE TABLE IF NOT EXISTS public.attendance_overtime (
          attendance_ot_id SERIAL PRIMARY KEY,
          attendance_id INT NOT NULL REFERENCES public.attendance(attendance_id) ON DELETE CASCADE,
          ot_request_id INT NOT NULL REFERENCES public.ot_requests(ot_request_id) ON DELETE RESTRICT,
          assignment_id INT NOT NULL REFERENCES public.employee_work_assignments(assignment_id) ON DELETE CASCADE,
          shift_id INT NOT NULL REFERENCES public.work_shifts(shift_id) ON DELETE RESTRICT,
          
          -- Check-in Data
          check_in_time TIMESTAMP WITH TIME ZONE NOT NULL,
          check_in_latitude NUMERIC(10, 8) NOT NULL,
          check_in_longitude NUMERIC(11, 8) NOT NULL,
          check_in_photo_url VARCHAR(500) NOT NULL,
          check_in_distance_meter NUMERIC(10, 2),
          matched_location_id INT NOT NULL REFERENCES public.work_locations(location_id),
          
          -- Check-out Data
          check_out_time TIMESTAMP WITH TIME ZONE,
          check_out_latitude NUMERIC(10, 8),
          check_out_longitude NUMERIC(11, 8),
          check_out_photo_url VARCHAR(500),
          check_out_distance_meter NUMERIC(10, 2),
          
          -- Status & Calculations
          attendance_status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
          actual_minutes INT DEFAULT 0,
          approved_minutes INT DEFAULT 0,
          
          -- Payroll Lock Status
          payroll_processed BOOLEAN NOT NULL DEFAULT FALSE,
          payroll_processed_at TIMESTAMP WITH TIME ZONE,
          
          -- Audit Metadata
          created_by INT NOT NULL REFERENCES public.accounts(account_id),
          updated_by INT REFERENCES public.accounts(account_id),
          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

          -- Constraints
          CONSTRAINT uq_ot_request_id UNIQUE (ot_request_id),
          CONSTRAINT chk_ot_times CHECK (check_out_time IS NULL OR check_out_time >= check_in_time)
      );

      CREATE INDEX IF NOT EXISTS idx_att_ot_attendance_id ON public.attendance_overtime(attendance_id);
      CREATE INDEX IF NOT EXISTS idx_att_ot_request_id ON public.attendance_overtime(ot_request_id);
      CREATE INDEX IF NOT EXISTS idx_att_ot_payroll_processed ON public.attendance_overtime(payroll_processed) WHERE payroll_processed = FALSE;
      CREATE INDEX IF NOT EXISTS idx_att_ot_composite_lookup ON public.attendance_overtime(assignment_id, shift_id);
    `);
  } catch (err) {
    console.warn('Failed to ensure database performance indexes:', err.message);
  }
}

pool.on('connect', () => {
  console.log('Database pool connected successfully.');
});

pool.on('error', (err) => {
  console.error('Unexpected error on idle database client', err);
});

// Run database migrations/index creation exactly once on application startup
initIndexes().catch(() => {});

module.exports = {
  pool,
  query: (text, params) => pool.query(text, params),
};
